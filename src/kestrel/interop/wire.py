"""SAPIENT on the wire: protobuf encoding, framing, validation, and TCP endpoints.

The rest of Kestrel builds SAPIENT messages as dictionaries in the proto3 JSON layout. This
module turns them into what a real SAPIENT link carries and back:

* **Encoding.** ``encode`` / ``decode`` convert between the dictionaries and BSI Flex 335 v2.0
  protobuf binary, using message classes built at import from the descriptor set compiled
  from Dstl's published schema (``sapient_v2.desc``, regenerated by
  ``scripts/gen_sapient_pb.py``). No generated code is checked in.
* **Validation.** ``violations`` checks what protobuf itself does not: the schema marks fields
  and oneofs ``is_mandatory`` through custom options, and a conformant receiver rejects
  messages without them. Everything Kestrel sends is checked against those options in the
  test suite, and the fusion service checks everything it receives.
* **Framing.** Each message on the TCP stream is preceded by its length as a 4-byte
  little-endian unsigned integer. ``FrameReader`` reassembles frames from arbitrary chunks
  and refuses a frame longer than ``MAX_FRAME`` instead of allocating it.
* **Endpoints.** ``SapientClient`` is the node side: it connects out, registers first on
  every (re)connection, stores and forwards while the link is down, and never blocks the
  caller. ``SapientServer`` is the fusion-node side: it accepts many nodes, routes by
  ``destination_id``, and binds each ``node_id`` to the connection that registered it.

The SAPIENT standard defines no transport security. Both endpoints take an optional
``ssl.SSLContext``; ``tls_context`` builds a mutual-TLS 1.3 one from a private CA, so only
holders of a certificate from that CA can register or task (see ``docs/security.md``).

"""

from __future__ import annotations

import contextlib
import logging
import queue
import socket
import ssl
import struct
import threading
import time
from collections import deque
from collections.abc import Callable
from importlib import resources
from typing import Any

Message = dict[str, Any]
MAX_FRAME = 1 << 20  # 1 MiB: far above any SAPIENT message Kestrel handles, far below memory
_PACKAGE = "sapient_msg.bsi_flex_335_v2_0"
_CONTENT = (
    "registration",
    "registration_ack",
    "status_report",
    "detection_report",
    "task",
    "task_ack",
    "alert",
    "alert_ack",
    "error",
)
log = logging.getLogger("kestrel.wire")


class WireError(ValueError):
    """A message or frame that cannot be encoded, decoded or accepted."""


class _Schema:
    """Message classes and mandatory-field options, built once from the descriptor set."""

    def __init__(self) -> None:
        try:
            from google.protobuf import descriptor_pb2, descriptor_pool, json_format, message_factory
        except ImportError as e:  # pragma: no cover - exercised only without the extra
            raise WireError("the SAPIENT wire format needs the protobuf package") from e
        self.json_format = json_format
        data = resources.files("kestrel.interop").joinpath("sapient_v2.desc").read_bytes()
        fds = descriptor_pb2.FileDescriptorSet()
        fds.ParseFromString(data)
        self.pool = descriptor_pool.DescriptorPool()
        for f in fds.file:
            self.pool.Add(f)
        self.message = message_factory.GetMessageClass(
            self.pool.FindMessageTypeByName(f"{_PACKAGE}.SapientMessage")
        )
        # custom options are extensions of FieldOptions/OneofOptions; read them by field number
        # from the raw descriptor protos so this works on every protobuf runtime
        self.mandatory_fields: dict[str, set[str]] = {}
        self.mandatory_oneofs: dict[str, dict[str, list[str]]] = {}
        ext_field = self._extension_number(fds, "field_options")
        ext_oneof = self._extension_number(fds, "oneof_options")
        for f in fds.file:
            for m in f.message_type:
                self._collect(f.package, m, ext_field, ext_oneof)

    @staticmethod
    def _extension_number(fds: Any, name: str) -> int:
        for f in fds.file:
            for ext in f.extension:
                if ext.name == name:
                    return int(ext.number)
        raise WireError(f"schema has no {name} extension")

    @staticmethod
    def _is_mandatory(options: Any, ext_number: int) -> bool:
        """Does a serialised options message carry ``{is_mandatory: true}`` in our extension?"""
        raw = options.SerializeToString()
        i = 0
        while i < len(raw):
            key, i = _varint(raw, i)
            number, kind = key >> 3, key & 7
            if kind == 2:
                size, i = _varint(raw, i)
                body, i = raw[i : i + size], i + size
                if number == ext_number:
                    j = 0
                    while j < len(body):
                        k, j = _varint(body, j)
                        v, j = _varint(body, j)
                        if k >> 3 == 1 and v:  # FieldOptions/OneofOptions.is_mandatory = 1
                            return True
            elif kind == 0:
                _, i = _varint(raw, i)
            elif kind == 5:
                i += 4
            elif kind == 1:
                i += 8
            else:  # pragma: no cover - groups do not occur in options
                break
        return False

    def _collect(self, package: str, m: Any, ext_field: int, ext_oneof: int) -> None:
        full = f"{package}.{m.name}"
        fields = set()
        oneofs: dict[str, list[str]] = {}
        for idx, o in enumerate(m.oneof_decl):
            members = [f.name for f in m.field if f.HasField("oneof_index") and f.oneof_index == idx]
            synthetic = len(members) == 1 and o.name == f"_{members[0]}"  # proto3 optional
            if not synthetic and self._is_mandatory(o.options, ext_oneof):
                oneofs[o.name] = members
        for f in m.field:
            if self._is_mandatory(f.options, ext_field):
                fields.add(f.name)
        self.mandatory_fields[full] = fields
        self.mandatory_oneofs[full] = oneofs
        for nested in m.nested_type:
            self._collect(full, nested, ext_field, ext_oneof)


def _varint(raw: bytes, i: int) -> tuple[int, int]:
    value, shift = 0, 0
    while True:
        b = raw[i]
        i += 1
        value |= (b & 0x7F) << shift
        if not b & 0x80:
            return value, i
        shift += 7


_schema: _Schema | None = None
_schema_lock = threading.Lock()


def schema() -> _Schema:
    global _schema
    with _schema_lock:
        if _schema is None:
            _schema = _Schema()
        return _schema


def _parse(msg: Message) -> Any:
    s = schema()
    pb = s.message()
    try:
        s.json_format.ParseDict(msg, pb, descriptor_pool=s.pool)
    except Exception as e:
        raise WireError(f"not a SAPIENT v2.0 message: {e}") from e
    return pb


def encode(msg: Message) -> bytes:
    """A SAPIENT message dictionary as BSI Flex 335 v2.0 protobuf binary."""
    out: bytes = _parse(msg).SerializeToString()
    return out


def decode(payload: bytes) -> Message:
    """Protobuf binary as a message dictionary (proto field names, enums by name)."""
    s = schema()
    pb = s.message()
    try:
        pb.ParseFromString(payload)
    except Exception as e:
        raise WireError(f"undecodable SAPIENT payload: {e}") from e
    out: Message = s.json_format.MessageToDict(pb, preserving_proto_field_name=True, descriptor_pool=s.pool)
    return out


def violations(msg: Message) -> list[str]:
    """Mandatory fields and oneofs of the standard that ``msg`` lacks (empty when conformant).

    Protobuf accepts a message with mandatory content missing; a SAPIENT receiver does not.
    """
    s = schema()
    pb = _parse(msg)
    out: list[str] = []

    def walk(m: Any, path: str) -> None:
        full = m.DESCRIPTOR.full_name
        present = {f.name for f, _ in m.ListFields()}
        for name in sorted(s.mandatory_fields.get(full, ())):
            if name not in present:
                out.append(f"{path}{name}")
        for name, members in s.mandatory_oneofs.get(full, {}).items():
            if not any(member in present for member in members):
                out.append(f"{path}{name} (one of {', '.join(members)})")
        for f, value in m.ListFields():
            if f.message_type is None or f.message_type.full_name.startswith("google."):
                continue
            if f.is_repeated if hasattr(f, "is_repeated") else f.label == f.LABEL_REPEATED:
                for k, item in enumerate(value):
                    walk(item, f"{path}{f.name}[{k}].")
            else:
                walk(value, f"{path}{f.name}.")

    walk(pb, "")
    return out


def content_kind(msg: Message) -> str:
    return next((k for k in _CONTENT if k in msg), "")


# --------------------------------------------------------------------------- framing


def frame(payload: bytes) -> bytes:
    if len(payload) > MAX_FRAME:
        raise WireError(f"message of {len(payload)} bytes exceeds the {MAX_FRAME}-byte frame limit")
    return struct.pack("<I", len(payload)) + payload


class FrameReader:
    """Reassembles length-prefixed frames from a byte stream delivered in arbitrary chunks."""

    def __init__(self, max_frame: int = MAX_FRAME) -> None:
        self.max_frame = max_frame
        self._buf = bytearray()

    def feed(self, data: bytes) -> list[bytes]:
        self._buf += data
        out = []
        while len(self._buf) >= 4:
            (size,) = struct.unpack_from("<I", self._buf)
            if size > self.max_frame:
                raise WireError(f"frame of {size} bytes exceeds the {self.max_frame}-byte limit")
            if len(self._buf) < 4 + size:
                break
            out.append(bytes(self._buf[4 : 4 + size]))
            del self._buf[: 4 + size]
        return out


def tls_context(ca: str, cert: str, key: str, server: bool) -> ssl.SSLContext:
    """Mutual TLS 1.3 against a private CA: both ends must present a certificate it signed."""
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER if server else ssl.PROTOCOL_TLS_CLIENT)
    ctx.minimum_version = ssl.TLSVersion.TLSv1_3
    ctx.load_verify_locations(cafile=ca)
    ctx.load_cert_chain(certfile=cert, keyfile=key)
    ctx.verify_mode = ssl.CERT_REQUIRED
    ctx.check_hostname = False  # nodes are addressed by IP in the field; the CA is the trust anchor
    return ctx


# --------------------------------------------------------------------------- node side


class SapientClient:
    """A node's connection to its fusion node or decision-making module.

    ``send`` never blocks and never raises on a dead link: messages wait in a bounded queue
    and go out in order when the connection returns. When the queue is full the oldest
    *status report* is dropped first (a stale status is no use late), then the oldest message.
    Registrations are remembered per node and sent first on every (re)connection, as the
    standard requires. Received messages are handed to ``on_message`` from the reader thread,
    or collected for ``poll``.
    """

    def __init__(
        self,
        host: str,
        port: int,
        on_message: Callable[[Message], None] | None = None,
        tls: ssl.SSLContext | None = None,
        queue_max: int = 5000,
        reconnect_s: tuple[float, float] = (1.0, 15.0),
        connect_timeout_s: float = 5.0,
    ) -> None:
        self.host, self.port, self.tls = host, port, tls
        self.on_message = on_message
        self.queue_max = queue_max
        self.reconnect_s = reconnect_s
        self.connect_timeout_s = connect_timeout_s
        self._out: deque[Message] = deque()
        self._registrations: dict[str, Message] = {}
        self._inbox: queue.SimpleQueue[Message] = queue.SimpleQueue()
        self._lock = threading.Lock()
        self._wake = threading.Event()
        self._running = False
        self._connected = False
        self._thread: threading.Thread | None = None
        self.sent = 0
        self.received = 0
        self.dropped = 0
        self.connections = 0
        self.last_rx_monotonic = 0.0

    @property
    def connected(self) -> bool:
        return self._connected

    def start(self) -> SapientClient:
        self._running = True
        self._thread = threading.Thread(target=self._run, name="sapient-client", daemon=True)
        self._thread.start()
        return self

    def close(self) -> None:
        self._running = False
        self._wake.set()
        if self._thread is not None:
            self._thread.join(timeout=3.0)

    def send(self, msg: Message) -> None:
        with self._lock:
            if "registration" in msg:
                self._registrations[str(msg.get("node_id", ""))] = msg
                if not self._connected:
                    return  # goes out first on connection
            while len(self._out) >= self.queue_max:
                stale = next((i for i, m in enumerate(self._out) if "status_report" in m), 0)
                del self._out[stale]
                self.dropped += 1
            self._out.append(msg)
        self._wake.set()

    def poll(self) -> list[Message]:
        out = []
        while True:
            try:
                out.append(self._inbox.get_nowait())
            except queue.Empty:
                return out

    def pending(self) -> int:
        with self._lock:
            return len(self._out)

    # ------------------------------------------------------------------ internals
    def _connect(self) -> socket.socket:
        sock = socket.create_connection((self.host, self.port), timeout=self.connect_timeout_s)
        sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_KEEPALIVE, 1)
        if self.tls is not None:
            sock = self.tls.wrap_socket(sock, server_hostname=self.host)
        sock.settimeout(0.2)
        return sock

    def _run(self) -> None:
        delay = self.reconnect_s[0]
        while self._running:
            try:
                sock = self._connect()
            except OSError as e:
                log.debug("connect to %s:%d failed: %s", self.host, self.port, e)
                self._wake.wait(delay)
                self._wake.clear()
                delay = min(delay * 2, self.reconnect_s[1])
                continue
            delay = self.reconnect_s[0]
            self.connections += 1
            try:
                self._session(sock)
            except (OSError, WireError) as e:
                log.warning("SAPIENT link to %s:%d lost: %s", self.host, self.port, e)
            finally:
                self._connected = False
                with contextlib.suppress(OSError):
                    sock.close()

    def _session(self, sock: socket.socket) -> None:
        with self._lock:
            first = list(self._registrations.values())
        for reg in first:
            sock.sendall(frame(encode(reg)))
            self.sent += 1
        self._connected = True
        reader = FrameReader()
        while self._running:
            while True:
                with self._lock:
                    if not self._out:
                        break
                    msg = self._out[0]
                try:
                    payload = frame(encode(msg))
                except WireError as e:  # never let one bad message block the queue
                    log.error("dropping unencodable message: %s", e)
                    payload = b""
                if payload:
                    sock.sendall(payload)  # on failure the message stays queued for the next link
                    self.sent += 1
                with self._lock:
                    if self._out and self._out[0] is msg:
                        self._out.popleft()
            try:
                data = sock.recv(65536)
            except (TimeoutError, ssl.SSLWantReadError):
                data = None
            if data == b"":
                raise OSError("closed by peer")
            if data:
                self.last_rx_monotonic = time.monotonic()
                for payload in reader.feed(data):
                    msg = decode(payload)
                    self.received += 1
                    if self.on_message is not None:
                        self.on_message(msg)
                    else:
                        self._inbox.put(msg)
            self._wake.clear()


# --------------------------------------------------------------------------- fusion side


class _Peer:
    def __init__(self, sock: socket.socket, addr: str) -> None:
        self.sock = sock
        self.addr = addr
        self.nodes: set[str] = set()
        self.lock = threading.Lock()
        self.alive = True

    def send(self, msg: Message) -> bool:
        try:
            payload = frame(encode(msg))
            with self.lock:
                self.sock.sendall(payload)
            return True
        except (OSError, WireError) as e:
            log.warning("send to %s failed: %s", self.addr, e)
            self.alive = False
            return False


class SapientServer:
    """The fusion-node end: accepts nodes, validates what they send, routes what it sends.

    Rules a connection must keep, each closing a way to corrupt the picture:

    * its first message is a registration; anything before one is discarded;
    * it may only speak for node ids it registered on this connection;
    * a node id held by another live connection cannot be taken over;
    * a frame over the size limit or an undecodable payload closes the connection;
    * a message lacking the standard's mandatory fields is answered with a SAPIENT ``Error``
      (or a rejecting ``RegistrationAck``) and not passed on.

    ``on_message`` receives each accepted message (from reader threads, serialised by a lock).
    """

    def __init__(
        self,
        host: str,
        port: int,
        on_message: Callable[[Message], None],
        node_id: str,
        tls: ssl.SSLContext | None = None,
        timestamp: Callable[[], str] | None = None,
        max_peers: int = 64,
    ) -> None:
        self.on_message = on_message
        self.node_id = node_id
        self.tls = tls
        self.max_peers = max_peers
        self._timestamp = timestamp or _utc_now
        self._listener = socket.create_server((host, port), reuse_port=False)
        self._listener.settimeout(0.2)
        self.port = int(self._listener.getsockname()[1])
        self._peers: list[_Peer] = []
        self._by_node: dict[str, _Peer] = {}
        self._lock = threading.Lock()
        self._deliver_lock = threading.Lock()
        self._running = False
        self._thread: threading.Thread | None = None
        self.rejected = 0
        self.accepted = 0

    def start(self) -> SapientServer:
        self._running = True
        self._thread = threading.Thread(target=self._accept, name="sapient-server", daemon=True)
        self._thread.start()
        return self

    def close(self) -> None:
        self._running = False
        if self._thread is not None:
            self._thread.join(timeout=3.0)
        with self._lock:
            peers = list(self._peers)
        for p in peers:
            with contextlib.suppress(OSError):
                p.sock.close()
        self._listener.close()

    def nodes(self) -> list[str]:
        with self._lock:
            return [n for n, p in self._by_node.items() if p.alive]

    def send(self, msg: Message) -> bool:
        """Send to the node named in ``destination_id``; False if it is not connected."""
        with self._lock:
            peer = self._by_node.get(str(msg.get("destination_id", "")))
        return peer is not None and peer.alive and peer.send(msg)

    # ------------------------------------------------------------------ internals
    def _accept(self) -> None:
        while self._running:
            try:
                sock, addr = self._listener.accept()
            except TimeoutError:
                continue
            except OSError:
                return
            with self._lock:
                self._peers = [p for p in self._peers if p.alive]
                full = len(self._peers) >= self.max_peers
            if full:
                sock.close()
                continue
            name = f"{addr[0]}:{addr[1]}"
            threading.Thread(
                target=self._serve, args=(sock, name), name=f"sapient-{name}", daemon=True
            ).start()

    def _reply(self, peer: _Peer, node: str, key: str, content: Message) -> None:
        peer.send(
            {"timestamp": self._timestamp(), "node_id": self.node_id, "destination_id": node, key: content}
        )

    def _serve(self, sock: socket.socket, addr: str) -> None:
        try:
            if self.tls is not None:
                sock = self.tls.wrap_socket(sock, server_side=True)
            sock.settimeout(0.5)
        except (OSError, ssl.SSLError) as e:
            log.warning("handshake with %s failed: %s", addr, e)
            with contextlib.suppress(OSError):
                sock.close()
            return
        peer = _Peer(sock, addr)
        with self._lock:
            self._peers.append(peer)
        reader = FrameReader()
        try:
            while self._running and peer.alive:
                try:
                    data = sock.recv(65536)
                except TimeoutError:
                    continue
                if not data:
                    break
                for payload in reader.feed(data):
                    self._handle(peer, decode(payload))
        except (OSError, WireError) as e:
            log.warning("closing %s: %s", addr, e)
        finally:
            peer.alive = False
            with self._lock:
                for n in peer.nodes:
                    if self._by_node.get(n) is peer:
                        del self._by_node[n]
            with contextlib.suppress(OSError):
                sock.close()

    def _handle(self, peer: _Peer, msg: Message) -> None:
        node = str(msg.get("node_id", ""))
        kind = content_kind(msg)
        missing = violations(msg) if kind else ["content"]
        if not node:
            missing.append("node_id")
        if kind == "registration":
            with self._lock:
                holder = self._by_node.get(node)
                taken = holder is not None and holder is not peer and holder.alive
                if not taken and not missing:
                    self._by_node[node] = peer
                    peer.nodes.add(node)
            reasons = (["node_id is registered on another connection"] if taken else []) + [
                f"missing mandatory field {m}" for m in missing
            ]
            ack: Message = {"acceptance": not reasons}
            if reasons:
                ack["ack_response_reason"] = reasons
                self.rejected += 1
            self._reply(peer, node, "registration_ack", ack)
            if reasons:
                return
        elif node not in peer.nodes:
            self.rejected += 1  # before registration, or speaking for a node it did not register
            return
        elif missing:
            self.rejected += 1
            self._reply(
                peer, node, "error", {"error_message": [f"missing mandatory field {m}" for m in missing]}
            )
            return
        self.accepted += 1
        with self._deliver_lock:
            self.on_message(msg)


def _utc_now() -> str:
    t = time.time()
    return time.strftime("%Y-%m-%dT%H:%M:%S", time.gmtime(t)) + f".{int(t % 1 * 1000):03d}Z"
